import { test, expect } from '@playwright/test';
test.skip(process.env.SIMULATION_TEST !== 'true', 'Run with SIMULATION_TEST=true');
test('Demo failure, cancellation, success and admin audit work on mobile without gateway calls', async ({ page }) => {
  await page.setViewportSize({ width: 390, height: 844 });
  const external = []; page.on('request', r => { if (r.url().includes('razorpay.com')) external.push(r.url()); });
  await page.goto('/login'); await page.getByRole('button', { name: 'Create an account' }).click();
  await page.getByLabel('Your name').fill('Simulation Browser Student');
  await page.getByLabel('Email address').fill('simulation-browser@test.local');
  await page.getByLabel('Password', { exact: true }).fill('Simulation2026!');
  await page.getByRole('button', { name: 'Create account', exact: false }).click();
  await expect(page).toHaveURL(/\/explore/);
  await page.goto('/premium');
  await page.getByRole('button', { name: 'Subscribe with demo payment' }).click();
  await expect(page.getByRole('heading', { name: 'Try a demo payment' })).toBeVisible();
  expect(await page.locator('input').count()).toBe(0);
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  await page.screenshot({ path: 'test-results/simulation-checkout-mobile.png', fullPage: true });
  await page.getByRole('button', { name: 'Simulate failed payment' }).click();
  await expect(page.getByRole('alert')).toContainText('Demo payment failed');
  await expect(page.getByRole('heading', { name: 'Preview only' })).toBeVisible();
  await page.getByRole('button', { name: 'Subscribe with demo payment' }).click();
  await page.getByRole('button', { name: 'Cancel demo payment' }).click();
  await expect(page.getByRole('status')).toContainText('Demo payment cancelled');
  await page.getByRole('button', { name: 'Subscribe with demo payment' }).click();
  await page.getByRole('button', { name: 'Simulate successful payment' }).click();
  await expect(page.getByRole('heading', { name: 'Subscription active' })).toBeVisible();
  await expect(page.getByRole('heading', { name: 'Choose your career direction' })).toBeVisible();
  await page.reload(); await expect(page.getByRole('heading', { name: 'Subscription active' })).toBeVisible();
  await expect(page.getByRole('row').filter({ hasText: 'Simulated · no money charged' })).toHaveCount(3);
  await page.goto('/tests'); await expect(page.getByRole('button', { name: 'Start practice' })).toBeVisible();
  await page.getByRole('button', { name: 'Sign out' }).click();
  await page.getByLabel('Email address').fill('admin@pathpilot.local');
  await page.getByLabel('Password', { exact: true }).fill('PilotLab2026!');
  await page.getByRole('button', { name: 'Sign in', exact: false }).click();
  await expect(page).toHaveURL('/admin');
  await page.goto('/admin/payments');
  const rows = page.getByRole('row').filter({ hasText: 'simulation-browser@test.local' });
  await expect(rows).toHaveCount(3);
  for (const row of await rows.all()) await expect(row).toContainText('Simulation');
  expect(external).toEqual([]);
});
